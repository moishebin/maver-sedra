#!/usr/bin/env node
/**
 * Generates lib/parshiot.ts: every parsha (including combined ones like
 * "Vayakhel-Pekudei") with its Hebrew name, aliyot and exact verse counts.
 *
 * Names and aliyot come from Hebcal (both diaspora and Israel schedules over
 * several years, so every split/combined form appears); verse counts come from
 * Sefaria's chapter lengths.
 *
 * Usage: node scripts/generate-parshiot.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT_FILE = fileURLToPath(new URL('../lib/parshiot.ts', import.meta.url));
const BOOKS = ['Genesis', 'Exodus', 'Leviticus', 'Numbers', 'Deuteronomy'];
const START_YEAR = 2024;
const END_YEAR = 2045;

// Read on Simchat Torah, so Hebcal never lists it as a weekly parashat event
const VEZOT_HABERAKHAH = {
  title: 'Parashat Vezot Haberakhah',
  hebrew: 'פרשת וזאת הברכה',
  leyning: {
    1: 'Deuteronomy 33:1-33:7',
    2: 'Deuteronomy 33:8-33:12',
    3: 'Deuteronomy 33:13-33:17',
    4: 'Deuteronomy 33:18-33:21',
    5: 'Deuteronomy 33:22-33:26',
    6: 'Deuteronomy 33:27-33:29',
    7: 'Deuteronomy 34:1-34:12',
  },
};

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
  return res.json();
}

function parseRange(range) {
  const m = range.match(/^(.+?)\s+(\d+):(\d+)-(\d+):(\d+)$/);
  if (!m) throw new Error(`Unparseable aliyah range: ${range}`);
  return {
    book: m[1],
    startChapter: +m[2],
    startVerse: +m[3],
    endChapter: +m[4],
    endVerse: +m[5],
  };
}

function countVerses(chapters, { startChapter, startVerse, endChapter, endVerse }) {
  if (startChapter === endChapter) return endVerse - startVerse + 1;
  let total = chapters[startChapter - 1] - startVerse + 1;
  for (let c = startChapter + 1; c < endChapter; c++) total += chapters[c - 1];
  return total + endVerse;
}

async function main() {
  const chapterLengths = {};
  for (const book of BOOKS) {
    const [shape] = await getJson(`https://www.sefaria.org/api/shape/${book}`);
    chapterLengths[book] = shape.chapters;
  }

  // Special Shabbatot (Rosh Chodesh, Shekalim, ...) shift the aliyah split, so
  // count each split per parsha and keep the usual one
  const variants = new Map();
  for (let year = START_YEAR; year <= END_YEAR; year++) {
    for (const il of ['off', 'on']) {
      const data = await getJson(
        `https://www.hebcal.com/hebcal?cfg=json&year=${year}&s=on&leyning=on&i=${il}`
      );
      for (const item of data.items) {
        if (item.category !== 'parashat') continue;
        const key = [1, 2, 3, 4, 5, 6, 7].map((i) => item.leyning[i]).join('|');
        const byKey = variants.get(item.title) ?? new Map();
        const seen = byKey.get(key);
        byKey.set(key, { event: item, count: (seen?.count ?? 0) + 1 });
        variants.set(item.title, byKey);
      }
    }
  }
  const events = new Map();
  for (const [title, byKey] of variants) {
    const best = [...byKey.values()].sort((a, b) => b.count - a.count)[0];
    events.set(title, best.event);
  }
  events.set(VEZOT_HABERAKHAH.title, VEZOT_HABERAKHAH);

  const parshiot = [...events.values()].map((event) => {
    const aliyot = [];
    for (let i = 1; i <= 7; i++) {
      const range = parseRange(event.leyning[i]);
      aliyot.push({
        number: i,
        ...range,
        verseCount: countVerses(chapterLengths[range.book], range),
      });
    }
    return {
      name: event.title.replace(/^Parashat /, ''),
      hebrewName: event.hebrew.replace(/^פרשת /, ''),
      book: aliyot[0].book,
      aliyot,
      totalVerses: aliyot.reduce((sum, a) => sum + a.verseCount, 0),
    };
  });

  // Torah order: book, then starting chapter/verse; a combined parsha sorts
  // right after its first half
  parshiot.sort((a, b) => {
    const [x, y] = [a.aliyot[0], b.aliyot[0]];
    return (
      BOOKS.indexOf(x.book) - BOOKS.indexOf(y.book) ||
      x.startChapter - y.startChapter ||
      x.startVerse - y.startVerse ||
      a.name.length - b.name.length
    );
  });

  // A combined parsha starts where its first half does, so it shares that number
  let num = 0;
  const entries = parshiot.map((p, i) => {
    const prev = parshiot[i - 1]?.aliyot[0];
    const start = p.aliyot[0];
    const sameStart =
      prev &&
      prev.book === start.book &&
      prev.startChapter === start.startChapter &&
      prev.startVerse === start.startVerse;
    if (!sameStart) num++;
    return { ...p, parshaNum: num };
  });

  const out = `// Generated by scripts/generate-parshiot.mjs. Do not edit by hand.
import { ParshaInfo } from '@/types';

export const PARSHIOT: ParshaInfo[] = ${JSON.stringify(entries, null, 2)};
`;
  writeFileSync(OUT_FILE, out);
  console.log(`Wrote ${entries.length} parshiot (${num} single) to ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
